import { setRequestLocale, getTranslations } from 'next-intl/server';
import { StaticPage } from '@/components/layout/static-page';
import { getConsentVersion } from '@/server/settings';

export default async function PrivacyPage({ params }: { params: Promise<{ locale: string }> }) {
  const { locale } = await params;
  setRequestLocale(locale);
  const t = await getTranslations('nav');
  const version = await getConsentVersion().catch(() => '1.0');

  return (
    <StaticPage title={t('privacy')} subtitle={`Версия документа: ${version}`}>
      <h2>1. Оператор и правовая основа</h2>
      <p>
        Обработка персональных данных обучающихся и работников осуществляется в соответствии
        с Законом Республики Казахстан «О персональных данных и их защите» и настоящей политикой.
        Обработка ведётся на основании согласия субъекта персональных данных, а также в целях
        исполнения образовательных обязательств вуза.
      </p>

      <h2>2. Состав обрабатываемых данных</h2>
      <p>Реализуется принцип минимизации — собираются только данные, необходимые для учебного процесса:</p>
      <ul>
        <li>индивидуальный идентификационный номер (ИИН);</li>
        <li>фамилия, имя, отчество;</li>
        <li>контактные данные: адрес электронной почты, номер телефона;</li>
        <li>сведения об образовательной программе, группе, форме и языке обучения;</li>
        <li>сведения об успеваемости и учебной активности.</li>
      </ul>

      <h2>3. Защита данных</h2>
      <ul>
        <li>ИИН хранится в зашифрованном виде (AES-256-GCM); в интерфейсе отображается маскированным, полностью — только ролям с соответствующим правом;</li>
        <li>пароли хранятся в виде хеша (bcrypt), в открытом виде не сохраняются;</li>
        <li>передача данных ведётся только по протоколу HTTPS;</li>
        <li>доступ к учебным материалам и сданным работам — только по подписанным ссылкам с ограниченным сроком действия;</li>
        <li>операции с персональными данными, изменения оценок и публикация курсов фиксируются в журнале аудита.</li>
      </ul>

      <h2>4. Место хранения данных</h2>
      <p>
        Персональные данные граждан Республики Казахстан подлежат хранению в базах данных,
        размещённых на территории Республики Казахстан. Промышленная эксплуатация Платформы
        с реальным контингентом допускается только после размещения баз данных на инфраструктуре,
        находящейся на территории РК. На этапе пилотной эксплуатации используются обезличенные
        или тестовые данные.
      </p>

      <h2>5. Сроки хранения</h2>
      <p>
        Данные обучающихся хранятся в течение срока обучения и последующего периода, установленного
        вузом. По истечении срока предусмотрена процедура обезличивания данных.
      </p>

      <h2>6. Права субъекта персональных данных</h2>
      <ul>
        <li>получить сведения о составе и целях обработки своих персональных данных;</li>
        <li>требовать изменения неточных данных;</li>
        <li>отозвать ранее данное согласие на обработку;</li>
        <li>обжаловать действия оператора в установленном законом порядке.</li>
      </ul>
      <p>
        Обращения направляются по адресу <a href="mailto:dpo@example.kz">dpo@example.kz</a>.
      </p>
    </StaticPage>
  );
}
